/**
 * Download the latin subsets of the three faces the dashboard uses into
 * frontend/public/fonts and emit the matching @font-face sheet.
 *
 * The app ships its fonts rather than calling Google at runtime, so the
 * dashboard renders identically offline and behind a registry proxy.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, "..");
const OUT_DIR = path.join(ROOT, "frontend", "public", "fonts");
const CSS_OUT = path.join(ROOT, "frontend", "app", "fonts.css");

const FAMILIES = [
  "Instrument+Serif:ital@0;1",
  "Instrument+Sans:wght@400;500;600",
  "IBM+Plex+Mono:wght@400;500",
];

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

const url = `https://fonts.googleapis.com/css2?${FAMILIES.map((f) => `family=${f}`).join("&")}&display=swap`;

const css = await (await fetch(url, { headers: { "User-Agent": UA } })).text();

// Google returns one block per (family, style, weight, subset); keep latin only.
const blocks = [...css.matchAll(/\/\* (?<subset>[a-z-]+) \*\/\s*@font-face \{(?<body>[^}]*)\}/g)];

fs.mkdirSync(OUT_DIR, { recursive: true });

const faces = [];
for (const block of blocks) {
  if (block.groups.subset !== "latin") continue;
  const body = block.groups.body;
  const family = /font-family: '([^']+)'/.exec(body)[1];
  const style = /font-style: (\w+)/.exec(body)[1];
  const weight = /font-weight: (\d+)/.exec(body)[1];
  const remote = /url\((https:[^)]+)\)/.exec(body)[1];
  const slug = `${family.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${weight}-${style}`;
  const file = `${slug}.woff2`;
  const target = path.join(OUT_DIR, file);
  if (!fs.existsSync(target)) {
    const bytes = Buffer.from(await (await fetch(remote, { headers: { "User-Agent": UA } })).arrayBuffer());
    fs.writeFileSync(target, bytes);
    console.log(`  ${file}  ${bytes.length} bytes`);
  } else {
    console.log(`  ${file}  cached`);
  }
  faces.push({ family, style, weight, file });
}

const sheet = [
  "/* Generated by scripts/fetchFonts.mjs. Do not edit by hand. */",
  ...faces.map(
    (face) => [
      "@font-face {",
      `  font-family: "${face.family}";`,
      `  font-style: ${face.style};`,
      `  font-weight: ${face.weight};`,
      "  font-display: swap;",
      `  src: url("/fonts/${face.file}") format("woff2");`,
      "  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;",
      "}",
    ].join("\n"),
  ),
  "",
].join("\n");

fs.writeFileSync(CSS_OUT, sheet, "utf-8");
console.log(`\n${faces.length} faces -> ${path.relative(ROOT, CSS_OUT)}`);
